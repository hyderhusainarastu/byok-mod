    SET_PRESETS = 0x29     # H->D, 1 + count*20 B -> ACK if requested
    GET_DOCSTATS = 0x2A    # H->D, 0 B -> DOCSTATS
    DOCSTATS = 0x2B        # D->H, 20 B: u32 files, words, bytes, newest_epoch, words_today
