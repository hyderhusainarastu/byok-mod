# ---------------------------------------------------------------------------
# CRC32 — §3.1
# ---------------------------------------------------------------------------

def crc32(data: bytes) -> int:
    """IEEE 802.3 / zlib CRC-32 exactly as §3.1 defines it: reflected poly
    0xEDB88320, init 0xFFFFFFFF, input/output reflected, final XOR
    0xFFFFFFFF. `zlib.crc32` already implements exactly this."""
    return zlib.crc32(data) & 0xFFFFFFFF


# ---------------------------------------------------------------------------
# Encoder
# ---------------------------------------------------------------------------

class EncodeError(ValueError):
    pass


def encode_frame(msg_type: int, flags: int, seq: int, payload: bytes = b"") -> bytes:
    """Builds one complete wire frame, per §3.

    Raises EncodeError if payload exceeds MAX_PAYLOAD, or if any field is
    out of its wire-representable range.
    """
    if len(payload) > MAX_PAYLOAD:
        raise EncodeError(
            f"payload_len {len(payload)} exceeds MAX_PAYLOAD {MAX_PAYLOAD}"
        )
    if not (0 <= msg_type <= 0xFF):
        raise EncodeError(f"type {msg_type} out of u8 range")
    if not (0 <= flags <= 0xFF):
        raise EncodeError(f"flags {flags} out of u8 range")
    if not (0 <= seq <= 0xFFFF):
        raise EncodeError(f"seq {seq} out of u16 range")

    header = struct.pack(
        "<BBBBBHH",
        MAGIC0, MAGIC1, VERSION, msg_type, flags, seq, len(payload),
    )
    body = header + payload
    crc = crc32(body)
    return body + struct.pack("<I", crc)


def frame_wire_size(payload_len: int) -> int:
    """Bytes a frame with this payload length will occupy on the wire."""
    return HEADER_LEN + payload_len + CRC_LEN


# ---------------------------------------------------------------------------
# Decoder
# ---------------------------------------------------------------------------

@dataclass
class Frame:
    """A fully decoded, CRC-verified frame."""
    version: int
    type: int
    flags: int
    seq: int
    payload: bytes

    # §7.5 sequence tracking, computed against the Parser instance's own
    # per-peer window (one Parser per direction of traffic).
    is_duplicate: bool = False  # SEQ seen in the last 8 distinct SEQs from
    # this peer, and type != FRAME_DATA (§7.5: "a duplicate FRAME_DATA is
    # not dropped").
    seq_gap: int = 0  # 0 = none; else frames missed before this one,
    # saturating at 255 (§7.5, §9 E_SEQ_GAP.detail). Always 0 when
    # is_duplicate is True.

    @property
    def len(self) -> int:
        return len(self.payload)


class ParseErrorCode(IntEnum):
    """Reasons the decoder rejects bytes and returns to HUNT (§7.7 step
    2/4). Maps directly to the NACK codes the caller should send, per §9."""
    BAD_VERSION = 1  # VERSION field not VERSION
    BAD_LENGTH = 2    # declared LEN > MAX_PAYLOAD
    BAD_CRC = 3       # CRC32 mismatch after a full frame arrived


@dataclass
class ParseError:
    err: ParseErrorCode
    header: bytes  # best-effort header bytes captured before the reject


# Internal state machine states, §7.7.
_HUNT = 0
_HEADER = 1
_PAYLOAD = 2
_CRC = 3


class Parser:
    """Incremental byte-stream parser/decoder (§7.7). Feed it bytes as they
    arrive, in any grouping — one byte at a time or in arbitrary chunks,
    the result is identical either way. Decoded frames and parse errors are
    delivered via the on_frame / on_error callbacks (or collect them from
    the feed() return value, see below).
    """

    def __init__(
        self,
        on_frame: Optional[Callable[[Frame], None]] = None,
        on_error: Optional[Callable[[ParseError], None]] = None,
    ) -> None:
        self.on_frame = on_frame
        self.on_error = on_error

        self._state = _HUNT
        self._buf = bytearray()
        self._hunt_stage = 0  # 0 = no partial magic seen; 1 = saw 0x42
        self._need_total = 0  # target len(self._buf) for the current frame

        self.resync_events = 0  # count of rejected frames (§7.7 note)

        # §7.5 per-peer SEQ window
        self._have_last_seq = False
        self._last_seq = 0
        self._seq_window: List[int] = []  # most-recent-last, capped at 8

    def reset_to_hunt(self) -> None:
        """Discard any partially-accumulated frame and return to HUNT,
        WITHOUT touching the SEQ window. Intended for the §7.6 200 ms
        mid-frame stall timeout, which the caller (owning a clock) detects
        and acts on; this module has no notion of time."""
        self._state = _HUNT
        self._hunt_stage = 0
        self._buf = bytearray()
        self._need_total = 0

    def new_session(self) -> None:
        """Forget the peer's last-seen SEQ and duplicate window, WITHOUT
        touching HUNT/framing state. §7.5: a host that (re)sends HELLO may
        restart its own SEQ counter anywhere; call this after a HELLO_ACK
        (transport.py's hello()) so the device's next frame isn't scored
        against a stale pre-reconnect last_seq. _track_sequence() also
        self-heals on a large forward jump, but this is the explicit,
        unambiguous signal."""
        self._have_last_seq = False
        self._last_seq = 0
        self._seq_window = []

    def feed(self, data: bytes) -> "tuple[List[Frame], List[ParseError]]":
        """Feed newly-arrived bytes into the parser. Processes them one at
        a time internally. Returns (frames, errors) decoded/raised during
        this call, in order, in addition to invoking on_frame/on_error for
        each (both mechanisms see the same events; use whichever is
        convenient)."""
        frames: List[Frame] = []
        errors: List[ParseError] = []
        for b in data:
            self._feed_byte(b, frames, errors)
        return frames, errors

    # -- internals --------------------------------------------------------

    def _feed_byte(self, b: int, frames: List[Frame], errors: List[ParseError]) -> None:
        if self._state == _HUNT:
            if b == MAGIC0:
                self._hunt_stage = 1
            elif self._hunt_stage == 1 and b == MAGIC1:
                self._buf = bytearray([MAGIC0, MAGIC1])
                self._hunt_stage = 0
                self._state = _HEADER
            else:
                self._hunt_stage = 0
            return

        if self._state == _HEADER:
            self._buf.append(b)
            if len(self._buf) == HEADER_LEN:
                version = self._buf[2]
                length = struct.unpack_from("<H", self._buf, 7)[0]

                if version != VERSION or length > MAX_PAYLOAD:
                    code = ParseErrorCode.BAD_VERSION if version != VERSION else ParseErrorCode.BAD_LENGTH
                    # Sec.7.7 step 2: "back to HUNT starting after the magic
                    # just consumed" -- not after the whole rejected header.
                    # Save the 7 post-magic bytes before reset_to_hunt()
                    # clears the buffer, then re-scan them for an embedded
                    # magic so a `42 4B` hiding inside a bad header isn't
                    # discarded with it. A full new header can't complete
                    # from this leftover alone, so this recurses at most
                    # once per rejected header.
                    saved = bytes(self._buf[2:HEADER_LEN])
                    self._reject(code, errors)
                    for sb in saved:
                        self._feed_byte(sb, frames, errors)
                    return

                self._need_total = HEADER_LEN + length + CRC_LEN
                self._state = _PAYLOAD if length != 0 else _CRC
            return

        if self._state == _PAYLOAD:
            self._buf.append(b)
            if len(self._buf) == self._need_total - CRC_LEN:
                self._state = _CRC
            return

        if self._state == _CRC:
            self._buf.append(b)
            if len(self._buf) == self._need_total:
                length = struct.unpack_from("<H", self._buf, 7)[0]
                computed = crc32(bytes(self._buf[: HEADER_LEN + length]))
                received = struct.unpack_from(
                    "<I", self._buf, HEADER_LEN + length
                )[0]

                if computed != received:
                    self._reject(ParseErrorCode.BAD_CRC, errors)
                    return

                frame = self._dispatch()
                frames.append(frame)
                if self.on_frame is not None:
                    self.on_frame(frame)
                self.reset_to_hunt()
            return

    def _reject(self, code: ParseErrorCode, errors: List[ParseError]) -> None:
        self.resync_events += 1
        err = ParseError(err=code, header=bytes(self._buf))
        errors.append(err)
        if self.on_error is not None:
            self.on_error(err)
        self.reset_to_hunt()

    def _dispatch(self) -> Frame:
        length = struct.unpack_from("<H", self._buf, 7)[0]
        version = self._buf[2]
        msg_type = self._buf[3]
        flags = self._buf[4]
        seq = struct.unpack_from("<H", self._buf, 5)[0]
        payload = bytes(self._buf[HEADER_LEN: HEADER_LEN + length])

        frame = Frame(
            version=version, type=msg_type, flags=flags, seq=seq, payload=payload
        )
        self._track_sequence(frame)
        return frame

    # A forward jump bigger than this is a new session, not a gap (§7.5's
    # "wild jump"), covering a reconnect that for whatever reason didn't
    # (re)call new_session() via a fresh HELLO.
    _SEQ_WILD_JUMP_THRESHOLD = 1024

    def _track_sequence(self, frame: Frame) -> None:
        """§7.5: fills is_duplicate/seq_gap on `frame`, and updates this
        parser's per-peer SEQ tracking state."""
        dup = frame.seq in self._seq_window and frame.type != Type.FRAME_DATA
        frame.is_duplicate = dup
        frame.seq_gap = 0

        if dup:
            # Retransmission of a known SEQ: not new, not a gap, and the
            # window/last_seq already reflect this SEQ from when it first
            # arrived -- nothing to advance.
            return

        if self._have_last_seq:
            # Wraps mod 2^16, so `diff` is only a meaningful "how far
            # forward" count in the low half of the range; the high half is
            # a SEQ that moved BACKWARD (e.g. diff=0xFFFF means -1). §7.5
            # blesses a backward/out-of-order FRAME_DATA retransmit
            # explicitly -- that must not be scored as a ~65535-frame gap,
            # and must not drag last_seq backward either, or the *next*
            # in-order frame would then look like a huge forward jump.
            diff = (frame.seq - self._last_seq) & 0xFFFF

            if diff == 0:
                # Exact repeat of the last-seen SEQ. Not a gap; state
                # already reflects it.
                return
            if diff > 0x8000:
                # Backward SEQ -- see above. Leave state untouched.
                return
            if diff > self._SEQ_WILD_JUMP_THRESHOLD:
                # §7.5: "a device that sees a wild jump treats it as a new
                # session, clears its duplicate window, and does not
                # complain."
                self._seq_window = []
            elif diff > 1:
                missed = diff - 1
                frame.seq_gap = min(missed, 255)

        self._have_last_seq = True
        self._last_seq = frame.seq
        self._seq_window.append(frame.seq)
        if len(self._seq_window) > 8:
            self._seq_window.pop(0)


