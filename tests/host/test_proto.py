class TestSpecVectors(unittest.TestCase):
    """docs/protocol.md §12: "these are normative"."""

    def test_vector_1_ping(self):
        frame = proto.encode_frame(proto.Type.PING, 0x00, 1, b"")
        expect = bytes.fromhex("424b0107000100000ofdbd5461".replace("o", "0"))
        self.assertEqual(frame, expect)
        self.assertEqual(proto.crc32(frame[:9]), 0x6154BDFD)

    def test_vector_2_hello(self):
        # Decoded payload per §12: proto_ver_min=1, proto_ver_max=1,
        # host_max_payload=4096, host_caps=0x0000000F
        payload = struct.pack("<BBHI", 1, 1, 4096, 0x0000000F)
        self.assertEqual(payload.hex(), "010100100f000000")

        frame = proto.encode_frame(proto.Type.HELLO, 0x01, 2, payload)
        expect = bytes.fromhex(
            "424b01010102000800010100100f0000004768e060"
        )
        self.assertEqual(frame, expect)
        self.assertEqual(proto.crc32(frame[:17]), 0x60E06847)

    def test_vector_3_clear(self):
        frame = proto.encode_frame(proto.Type.CLEAR, 0x00, 3, b"\x00")
        expect = bytes.fromhex("424b011000030001000086ae14c8")
        self.assertEqual(frame, expect)
        self.assertEqual(proto.crc32(frame[:10]), 0xC814AE86)

    def test_vector_4_set_backlight(self):
        payload = bytes.fromhex("80f401")
        frame = proto.encode_frame(proto.Type.SET_BACKLIGHT, 0x01, 4, payload)
        expect = bytes.fromhex("424b0121010400030080f40187dd0bb1")
        self.assertEqual(frame, expect)
        self.assertEqual(proto.crc32(frame[:12]), 0xB10BDD87)

        level, fade_ms = struct.unpack("<BH", payload)
        self.assertEqual(level, 128)
        self.assertEqual(fade_ms, 500)

    def test_vector_5_draw_text_worked_example(self):
        # §11 worked example, reused verbatim as §12 vector #5.
        payload = struct.pack("<HHBBH", 4, 8, 1, 0, 4) + b"BYOK"
        frame = proto.encode_frame(proto.Type.DRAW_TEXT, 0x01, 5, payload)
        expect = bytes.fromhex(
            "42 4b 01 11 01 05 00 0c 00 04 00 08 00 01 00 04 00 42 59 4f 4b e8 28 c7 14".replace(" ", "")
        )
        self.assertEqual(frame, expect)
        self.assertEqual(len(frame), 25)
        self.assertEqual(proto.crc32(frame[:21]), 0x14C728E8)

    def test_vector_6_checkerboard_crc(self):
        self.assertEqual(proto.crc32(b"\xAA" * 16), 0xC79B40E0)

    def test_reference_generator_from_spec_matches_our_encoder(self):
        """The exact `build()` helper printed in docs/protocol.md §12,
        reproduced here so a change to our encoder that silently diverges
        from the spec's own reference snippet fails loudly."""

        def build(msg_type, flags, seq, payload=b""):
            hdr = proto.MAGIC0.to_bytes(1, "little") + proto.MAGIC1.to_bytes(1, "little")
            hdr += bytes([proto.VERSION, msg_type, flags])
            hdr += struct.pack("<HH", seq, len(payload))
            body = hdr + payload
            return body + struct.pack("<I", zlib.crc32(body) & 0xFFFFFFFF)

        for msg_type, flags, seq, payload in [
            (proto.Type.PING, 0x00, 1, b""),
            (proto.Type.HELLO, 0x01, 2, struct.pack("<BBHI", 1, 1, 4096, 0x0F)),
            (proto.Type.CLEAR, 0x00, 3, b"\x00"),
        ]:
            self.assertEqual(
                proto.encode_frame(msg_type, flags, seq, payload),
                build(msg_type, flags, seq, payload),
            )


# ---------------------------------------------------------------------------
# Cross-check against the C implementation's actual output
# ---------------------------------------------------------------------------

class TestCrossCheckAgainstC(unittest.TestCase):
    """tests/proto/vectors.json is written by tests/proto/test_proto.c using
    the real C encoder (byok_frame_encode). If this file is missing, run
    `make -C tests/proto test` first -- that is also what a CI job is
    expected to do before this suite."""

    @classmethod
    def setUpClass(cls):
        if not os.path.exists(VECTORS_JSON_PATH):
            raise unittest.SkipTest(
                f"{VECTORS_JSON_PATH} not found; run "
                f"'make -C tests/proto test' to generate it first"
            )
        with open(VECTORS_JSON_PATH, "r") as f:
            cls.vectors = json.load(f)

    def test_vectors_json_is_nonempty(self):
        self.assertGreater(len(self.vectors), 0)

    def test_python_encoder_matches_c_encoder_output(self):
        for v in self.vectors:
            with self.subTest(name=v["name"]):
                payload = bytes.fromhex(v["payload_hex"])
                frame = proto.encode_frame(v["type"], v["flags"], v["seq"], payload)
                expect = bytes.fromhex(v["frame_hex"])
                self.assertEqual(
                    frame, expect,
                    f"{v['name']}: python encoder diverges from C encoder output",
                )
                self.assertEqual(proto.crc32(frame[: 9 + len(payload)]), v["crc32"])

    def test_python_decoder_recovers_c_encoded_vectors(self):
        for v in self.vectors:
            with self.subTest(name=v["name"]):
                wire = bytes.fromhex(v["frame_hex"])
                frames = []
                errors = []
                p = proto.Parser(on_frame=frames.append, on_error=errors.append)
                p.feed(wire)

                self.assertEqual(errors, [])
                self.assertEqual(len(frames), 1)
                f = frames[0]
                self.assertEqual(f.type, v["type"])
                self.assertEqual(f.flags, v["flags"])
                self.assertEqual(f.seq, v["seq"])
                self.assertEqual(f.payload, bytes.fromhex(v["payload_hex"]))
                self.assertFalse(f.is_duplicate)
                self.assertEqual(f.seq_gap, 0)


