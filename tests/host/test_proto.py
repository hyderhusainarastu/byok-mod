# ---------------------------------------------------------------------------
# Fuzz: random bytes must never raise
# ---------------------------------------------------------------------------

class TestFuzz(unittest.TestCase):
    def test_fuzz_random_bytes_never_crashes(self):
        import random

        rng = random.Random(0xB4B0C)
        p = proto.Parser()

        # Python's per-call overhead makes a full 10**6-iteration loop slow;
        # the C suite (tests/proto, run under ASan/UBSan) owns the
        # authoritative 10**6-iteration fuzz requirement. This exercises the
        # same feed() path with a meaningful but CI-friendly byte count and
        # asserts the parser is still healthy afterwards.
        total_bytes = 200_000
        chunk = bytearray(8)
        fed = 0
        while fed < total_bytes:
            n = rng.randint(1, len(chunk))
            for i in range(n):
                chunk[i] = rng.randrange(256)
            p.feed(bytes(chunk[:n]))
            fed += n

        # Parser must still be functional after all that noise.
        frames = []
        p.on_frame = frames.append
        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 1))
        self.assertEqual(len(frames), 1)


