class TestStreamBehaviour(unittest.TestCase):
    def test_truncated_frame_then_completion(self):
        payload = struct.pack("<HHBBH", 4, 8, 1, 0, 4) + b"BYOK"
        frame = proto.encode_frame(proto.Type.DRAW_TEXT, 0x01, 5, payload)
        self.assertEqual(len(frame), 25)

        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)

        p.feed(frame[:10])
        self.assertEqual(frames, [])
        self.assertEqual(errors, [])

        p.feed(frame[10:])
        self.assertEqual(errors, [])
        self.assertEqual(len(frames), 1)
        self.assertEqual(frames[0].type, proto.Type.DRAW_TEXT)
        self.assertEqual(frames[0].payload, payload)

    def test_garbage_before_magic_is_discarded(self):
        real = proto.encode_frame(proto.Type.GET_STATUS, 0x00, 42)
        noise = bytes([0x00, 0xFF, 0x42, 0x00, 0x4B, 0x42, 0x42, 0x01, 0x99, 0x10, 0x20, 0x30])

        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)
        p.feed(noise + real)

        self.assertEqual(errors, [])
        self.assertEqual(len(frames), 1)
        self.assertEqual(frames[0].type, proto.Type.GET_STATUS)
        self.assertEqual(frames[0].seq, 42)

    def test_back_to_back_frames_in_one_chunk(self):
        f1 = proto.encode_frame(proto.Type.PING, 0x00, 1)
        f2 = proto.encode_frame(proto.Type.CLEAR, 0x00, 2, b"\x01")
        f3 = proto.encode_frame(proto.Type.GET_BATTERY, 0x00, 3)

        frames = []
        p = proto.Parser(on_frame=frames.append)
        p.feed(f1 + f2 + f3)

        self.assertEqual(len(frames), 3)
        self.assertEqual([f.type for f in frames],
                          [proto.Type.PING, proto.Type.CLEAR, proto.Type.GET_BATTERY])
        self.assertEqual([f.seq for f in frames], [1, 2, 3])

    def test_frame_split_across_one_byte_feeds(self):
        payload = bytes(range(10))
        frame = proto.encode_frame(proto.Type.DRAW_RECT, 0x01, 77, payload)

        frames = []
        p = proto.Parser(on_frame=frames.append)
        for i in range(len(frame)):
            p.feed(frame[i: i + 1])
            if i + 1 < len(frame):
                self.assertEqual(frames, [])

        self.assertEqual(len(frames), 1)
        self.assertEqual(frames[0].type, proto.Type.DRAW_RECT)
        self.assertEqual(frames[0].payload, payload)

    def test_feed_return_value_matches_callbacks(self):
        f1 = proto.encode_frame(proto.Type.PING, 0x00, 1)
        f2 = proto.encode_frame(proto.Type.PONG, 0x00, 2)

        seen = []
        p = proto.Parser(on_frame=seen.append)
        frames, errors = p.feed(f1 + f2)

        self.assertEqual(errors, [])
        self.assertEqual(len(frames), 2)
        self.assertEqual(frames, seen)


