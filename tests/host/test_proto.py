class TestRoundTripAllTypes(unittest.TestCase):
    TYPE_PAYLOAD_LENS = [
        (proto.Type.HELLO, 8),
        (proto.Type.HELLO_ACK, 32),
        (proto.Type.GET_INFO, 0),
        (proto.Type.INFO, 64),
        (proto.Type.GET_STATUS, 0),
        (proto.Type.STATUS, 20),
        (proto.Type.PING, 0),
        (proto.Type.PING, 4),
        (proto.Type.PONG, 0),
        (proto.Type.PONG, 4),
        (proto.Type.ACK, 0),
        (proto.Type.NACK, 4),
        (proto.Type.CLEAR, 1),
        (proto.Type.DRAW_TEXT, 12),
        (proto.Type.DRAW_RECT, 10),
        (proto.Type.DRAW_BITMAP, 18),
        (proto.Type.FRAME_BEGIN, 8),
        (proto.Type.FRAME_DATA, 16),
        (proto.Type.FRAME_END, 5),
        (proto.Type.PARTIAL_REFRESH, 8),
        (proto.Type.FULL_REFRESH, 1),
        (proto.Type.SET_MODE, 2),
        (proto.Type.SET_BACKLIGHT, 3),
        (proto.Type.SET_CONTRAST, 1),
        (proto.Type.GET_BATTERY, 0),
        (proto.Type.BATTERY, 8),
        (proto.Type.REBOOT, 2),
        (proto.Type.BOOT_ORIGINAL, 4),
        (proto.Type.EVT_BUTTON, 6),
        (proto.Type.EVT_STATUS, 20),
        (proto.Type.EVT_LOG, 10),
    ]

    def test_round_trip(self):
        for i, (msg_type, plen) in enumerate(self.TYPE_PAYLOAD_LENS):
            with self.subTest(type=msg_type, payload_len=plen):
                payload = bytes((msg_type * 31 + j * 7 + i) & 0xFF for j in range(plen))
                seq = 1000 + i
                frame = proto.encode_frame(msg_type, proto.Flags.ACK_REQ, seq, payload)
                self.assertEqual(len(frame), proto.frame_wire_size(plen))

                frames, errors = proto.Parser().feed(frame)
                self.assertEqual(errors, [])
                self.assertEqual(len(frames), 1)
                f = frames[0]
                self.assertEqual(f.version, proto.VERSION)
                self.assertEqual(f.type, msg_type)
                self.assertEqual(f.seq, seq)
                self.assertEqual(f.payload, payload)
                self.assertFalse(f.is_duplicate)
                self.assertEqual(f.seq_gap, 0)


