# §7.5 sequence tracking: duplicates and gaps
# ---------------------------------------------------------------------------

class TestSequenceTracking(unittest.TestCase):
    def test_duplicate_seq_flagged_for_idempotent_types(self):
        frame = proto.encode_frame(proto.Type.PING, 0x00, 100)

        frames = []
        p = proto.Parser(on_frame=frames.append)
        p.feed(frame)
        self.assertFalse(frames[-1].is_duplicate)

        p.feed(frame)  # exact same bytes again
        self.assertEqual(len(frames), 2)
        self.assertTrue(frames[-1].is_duplicate)
        self.assertEqual(frames[-1].seq_gap, 0)

    def test_frame_data_exempt_from_dedup(self):
        frame = proto.encode_frame(proto.Type.FRAME_DATA, 0x00, 200, bytes(8))

        frames = []
        p = proto.Parser(on_frame=frames.append)
        p.feed(frame)
        self.assertFalse(frames[-1].is_duplicate)
        p.feed(frame)  # retransmit same chunk
        self.assertFalse(frames[-1].is_duplicate)

    def test_seq_gap_detection_and_saturation(self):
        frames = []
        p = proto.Parser(on_frame=frames.append)

        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 10))
        self.assertEqual(frames[-1].seq_gap, 0)

        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 15))  # missed 11,12,13,14
        self.assertEqual(frames[-1].seq_gap, 4)
        self.assertFalse(frames[-1].is_duplicate)

        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 16))  # consecutive
        self.assertEqual(frames[-1].seq_gap, 0)

        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 1000))  # far jump
        self.assertEqual(frames[-1].seq_gap, 255)  # saturates

    def test_backward_retransmit_not_scored_as_gap(self):
        """Regression: (seq - last_seq) & 0xFFFF used to wrap a BACKWARD
        step into a ~65535-frame "gap", and clobbered last_seq backward
        too, so the *next* in-order frame then looked like a huge forward
        jump. §7.5 explicitly blesses a backward/retransmitted FRAME_DATA
        chunk ("chunk retransmission is legitimate and offset-addressed")."""
        payload = bytes(8)
        frames = []
        p = proto.Parser(on_frame=frames.append)

        for seq in (1, 2, 3):
            p.feed(proto.encode_frame(proto.Type.FRAME_DATA, 0x00, seq, payload))
            self.assertEqual(frames[-1].seq_gap, 0)

        # Retransmit of an EARLIER chunk (seq 1, not the last-seen seq 3).
        p.feed(proto.encode_frame(proto.Type.FRAME_DATA, 0x00, 1, payload))
        self.assertEqual(frames[-1].seq_gap, 0)
        self.assertFalse(frames[-1].is_duplicate)  # FRAME_DATA is dedup-exempt

        # The NEXT in-order frame (seq 4) must still read as a clean single
        # step, not a huge gap from the backward seq 1 having overwritten
        # last_seq.
        p.feed(proto.encode_frame(proto.Type.FRAME_DATA, 0x00, 4, payload))
        self.assertEqual(frames[-1].seq_gap, 0)

    def test_wild_forward_jump_is_new_session(self):
        frames = []
        p = proto.Parser(on_frame=frames.append)

        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 10))
        self.assertEqual(frames[-1].seq_gap, 0)

        # Forward jump well past the wild-jump threshold but well under the
        # halfway point of u16 wrap space (so it reads unambiguously as
        # "forward far", not a small backward step).
        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 20000))
        self.assertEqual(frames[-1].seq_gap, 0)
        self.assertFalse(frames[-1].is_duplicate)

        # The old SEQ (10) is no longer in the (cleared) duplicate window.
        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 10))
        self.assertFalse(frames[-1].is_duplicate)

    def test_new_session_clears_tracking_without_touching_framing(self):
        frames = []
        p = proto.Parser(on_frame=frames.append)

        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 9000))
        self.assertEqual(len(frames), 1)

        p.new_session()

        # A host that reconnected and restarted its SEQ at 1 must not look
        # like a huge gap, or a duplicate.
        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 1))
        self.assertEqual(len(frames), 2)
        self.assertEqual(frames[-1].seq_gap, 0)
        self.assertFalse(frames[-1].is_duplicate)


