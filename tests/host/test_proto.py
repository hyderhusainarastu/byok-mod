# Malformed / oversized length, bad CRC, resync behaviour
# ---------------------------------------------------------------------------

class TestMalformedFrames(unittest.TestCase):
    def test_malformed_length_caught_by_crc(self):
        # Valid CLEAR frame (LEN=1), then corrupt just the LEN field to a
        # different in-range value. The CRC (computed by the sender over
        # the true bytes) then necessarily fails to verify -- see the
        # identical C test for the full rationale.
        frame = bytearray(proto.encode_frame(proto.Type.CLEAR, 0x00, 9, b"\x00"))
        self.assertEqual(len(frame), 14)
        frame[7] = 5  # LEN low byte: 1 -> 5
        frame[8] = 0

        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)
        p.feed(bytes(frame) + bytes(16))  # padding so the CRC field is reachable

        self.assertEqual(frames, [])
        self.assertEqual(len(errors), 1)
        self.assertEqual(errors[0].err, proto.ParseErrorCode.BAD_CRC)

    def test_oversized_length_rejected(self):
        header = bytes([0x42, 0x4B, 0x01, 0x07, 0x00]) + struct.pack("<HH", 0x2A, 0xFFFF)
        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)
        p.feed(header)

        self.assertEqual(frames, [])
        self.assertEqual(len(errors), 1)
        self.assertEqual(errors[0].err, proto.ParseErrorCode.BAD_LENGTH)
        self.assertEqual(p.resync_events, 1)

        # Resyncs cleanly: a following valid frame decodes normally.
        p.feed(proto.encode_frame(proto.Type.PING, 0x00, 1))
        self.assertEqual(len(frames), 1)
        self.assertEqual(frames[0].type, proto.Type.PING)

    def test_bad_crc_rejected(self):
        frame = bytearray(
            proto.encode_frame(proto.Type.SET_BACKLIGHT, 0x01, 4, bytes.fromhex("80f401"))
        )
        frame[-1] ^= 0xFF

        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)
        p.feed(bytes(frame))

        self.assertEqual(frames, [])
        self.assertEqual(len(errors), 1)
        self.assertEqual(errors[0].err, proto.ParseErrorCode.BAD_CRC)

    def test_bad_version_rejected_before_crc(self):
        frame = bytearray(proto.encode_frame(proto.Type.PING, 0x00, 7))
        frame[2] = 0x02  # VERSION: 1 -> 2

        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)
        p.feed(bytes(frame))

        self.assertEqual(frames, [])
        self.assertEqual(len(errors), 1)
        self.assertEqual(errors[0].err, proto.ParseErrorCode.BAD_VERSION)

    def test_encode_rejects_oversized_payload(self):
        with self.assertRaises(proto.EncodeError):
            proto.encode_frame(proto.Type.DRAW_BITMAP, 0x00, 1, bytes(proto.MAX_PAYLOAD + 1))

    def test_bad_header_recovers_embedded_magic(self):
        """Regression: §7.7 step 2 says a rejected header sends the
        receiver "back to HUNT starting after the magic just consumed" --
        not after the whole rejected header. A `42 4B` sitting inside a
        bad header must still be found, not discarded along with it."""
        real_frame = proto.encode_frame(proto.Type.PING, 0x00, 555)

        # 5-byte bogus prefix: magic, an invalid VERSION, then two
        # don't-care bytes (TYPE, FLAGS) -- rejected on VERSION before LEN
        # is even inspected.
        stream = bytes([0x42, 0x4B, 0xFF, 0x00, 0x00]) + real_frame

        frames = []
        errors = []
        p = proto.Parser(on_frame=frames.append, on_error=errors.append)
        p.feed(stream)

        self.assertEqual(len(errors), 1)
        self.assertEqual(errors[0].err, proto.ParseErrorCode.BAD_VERSION)
        self.assertEqual(len(frames), 1)  # the embedded frame was still found
        self.assertEqual(frames[0].type, proto.Type.PING)
        self.assertEqual(frames[0].seq, 555)


